# ── XAI explanation renderer ─────────────────────────────────────────

def localize_xai(checks, recommendation, language):
    """Render a full XAI explanation from structured check/recommendation data."""
    if language == "Kannada":
        lines = ["**ಮುಖ್ಯ ಅಂಶಗಳು:**"]
        for feature, status in checks:
            lines.append(f"- {localize_feature(feature, language)}: {localize_status(status, language)}")
        lines.append("")
        concern = [(f, s) for f, s in checks if "suitable" not in s.lower()]
        if not concern:
            lines.append(f"**ಶಿಫಾರಸು:** ಪ್ರಸ್ತುತ ಪರಿಸ್ಥಿತಿಗಳನ್ನು ಕಾಪಾಡಿ ಮತ್ತು ಮೇಲ್ವಿಚಾರಣೆಯನ್ನು ಮುಂದುವರಿಸಿ.")
        else:
            names = ", ".join(localize_feature(f, language) for f, _ in concern)
            lines.append(f"**ಶಿಫಾರಸು:** {names} ಗೆ ಆದ್ಯತೆ ನೀಡಿ; ಒಂದು ಸಮಯದಲ್ಲಿ ಒಂದು ಅಂಶವನ್ನು ಸರಿಹೊಂದಿಸಿ ಮತ್ತು ಸಂವೇದಕಗಳನ್ನು ಮರುಪರಿಶೀಲಿಸಿ.")
        return "\n".join(lines)
    else:
        lines = ["**Main factors:**"]
        for feature, status in checks:
            lines.append(f"- {feature}: {status}")
        lines.append("")
        lines.append(f"**Recommendation:** {recommendation}")
        return "\n".join(lines)


