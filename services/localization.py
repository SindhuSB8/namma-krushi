def localize_disease(name, language):
    """Map a canonical CNN class name to the farmer-facing display name."""
    table = _DISEASE_KN if language == "Kannada" else _DISEASE_EN
    result = table.get(name)
    if result:
        return result
    # Older database rows replaced model underscores with spaces. Compare a
    # punctuation-insensitive form so those rows localize correctly too.
    normalized = re.sub(r"[^a-z0-9]+", "", name.lower())
    for canonical, display in table.items():
        if re.sub(r"[^a-z0-9]+", "", canonical.lower()) == normalized:
            return display
    return name.replace("_", " ").title()

