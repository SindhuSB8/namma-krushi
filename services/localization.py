def _has_kannada(text):
    return any("\u0c80" <= character <= "\u0cff" for character in (text or ""))


def localize_chat_title(title, language):
    """Give legacy English sessions a useful Kannada topic label."""
    title = (title or "").strip()
    if language != "Kannada" or _has_kannada(title):
        return title
    lowered = title.lower()
    topics = (
        (("water", "irrigation", "moisture"), "ಟೊಮ್ಯಾಟೊ ನೀರಾವರಿ ಸಲಹೆ"),
        (("soil", "root", "media"), "ಮಣ್ಣು ಮತ್ತು ಬೇರು ವಲಯದ ಸಲಹೆ"),
        (("pest", "insect", "whitefly", "borer"), "ಕೀಟ ನಿರ್ವಹಣೆಯ ಸಲಹೆ"),
        (("disease", "leaf", "spot", "blight", "wilt"), "ಎಲೆ ಮತ್ತು ರೋಗದ ಸಲಹೆ"),
        (("scheme", "subsidy", "loan", "insurance"), "ಸರ್ಕಾರಿ ಯೋಜನೆಯ ಸಲಹೆ"),
        (("greenhouse", "polyhouse", "temperature", "humidity"), "ಹಸಿರುಮನೆ ಸಲಹೆ"),
        (("grow", "yield", "tomato", "home"), "ಟೊಮ್ಯಾಟೊ ಬೆಳೆ ಸಲಹೆ"),
    )
    for keywords, label in topics:
        if any(keyword in lowered for keyword in keywords):
            return label
    return "ಹಿಂದಿನ ಕೃಷಿ ಸಂಭಾಷಣೆ"


def localize_chat_message(message, language, other_language_notice):
    """Do not leak old English-only history when the page is in Kannada."""
    message = message or ""
    if language == "Kannada" and re.search(r"[A-Za-z]", message) and not _has_kannada(message):
        return other_language_notice
    return message
